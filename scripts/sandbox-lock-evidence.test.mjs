// node --test scripts/sandbox-lock-evidence.test.mjs
//
// The sbx Python lock's supply-chain evidence (07.17.1.1.1 D-01, PD-14, A-06): the pure checks over fixture objects
// shaped like the real responses (PyPI `/pypi/<name>/<version>/json`, OSV `querybatch`, the GSD legitimacy seam).
// Offline: nothing here touches the network.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { describe, it } from "node:test";
import {
  ageCheck,
  closureCheck,
  evidence,
  installedCheck,
  KNOWN_PROJECTS,
  legitimacyCheck,
  osvCheck,
  parseLock,
  yankCheck,
} from "./sandbox-lock-evidence.mjs";

const NOW = "2026-11-12T12:00:00Z";
const DAY = 86_400_000;
const ago = (days) => new Date(Date.parse(NOW) - days * DAY).toISOString();
const h = (c) => c.repeat(64);

const LOCK = [
  "#",
  "# This file is autogenerated by pip-compile with Python 3.11",
  "#",
  "--only-binary :all:",
  "",
  "alpha==1.0.0 \\",
  `    --hash=sha256:${h("a")} \\`,
  `    --hash=sha256:${h("b")}`,
  "    # via -r requirements.in",
  "Beta_Lib==2.0.0 \\",
  `    --hash=sha256:${h("c")}`,
  "    # via",
  "    #   -r requirements.in",
  "    #   alpha",
  "gamma==3.0.0 \\",
  `    --hash=sha256:${h("d")}`,
  "    # via beta-lib",
  "",
].join("\n");
const IN = "# comment\nalpha\nBeta.Lib<2.1\n";

const file = (sha256, days, extra = {}) => ({
  filename: `f-${sha256.slice(0, 4)}.whl`,
  digests: { sha256 },
  upload_time_iso_8601: ago(days),
  yanked: false,
  ...extra,
});
const release = (name, version, files, info = {}) => ({
  info: {
    name,
    version,
    yanked: false,
    home_page: null,
    project_urls: { Source: `https://github.com/example/${name}` },
    ...info,
  },
  urls: files,
});
const KNOWN = {
  alpha: ["github.com/example/alpha"],
  "beta-lib": ["github.com/example/beta-lib"],
  gamma: ["github.com/example/gamma"],
};
const seam = (name, verdict = "SUS") => ({
  name,
  verdict,
  signals: { exists: true },
  reasons: ["unknown-downloads"],
});

describe("parseLock", () => {
  it("returns PEP 503 names, versions, hashes and via parents, single- and multi-line", () => {
    assert.deepEqual(parseLock(LOCK), [
      { name: "alpha", version: "1.0.0", hashes: [h("a"), h("b")], via: ["-r requirements.in"] },
      { name: "beta-lib", version: "2.0.0", hashes: [h("c")], via: ["-r requirements.in", "alpha"] },
      { name: "gamma", version: "3.0.0", hashes: [h("d")], via: ["beta-lib"] },
    ]);
  });
});

describe("ageCheck (a)", () => {
  const pin = { name: "alpha", version: "1.0.0", hashes: [h("a"), h("b")] };

  it("passes when every hashed file is a file of the release uploaded at least 14 days ago", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30), file(h("b"), 14), file(h("e"), 1)]);
    const res = ageCheck(pin, r, NOW);
    assert.equal(res.ok, true);
    assert.equal(res.holdBack, null);
    assert.equal(res.files.length, 2);
  });

  it("fails on a hashed file uploaded less than 14 days ago and returns the hold-back", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30), file(h("b"), 13.9)]);
    const res = ageCheck(pin, r, NOW);
    assert.equal(res.ok, false);
    assert.equal(res.holdBack, "alpha<1.0.0");
    assert.deepEqual(res.tooNew, ["f-bbbb.whl"]);
  });

  it("honours another minimum age", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30), file(h("b"), 20)]);
    assert.equal(ageCheck(pin, r, NOW, 21).ok, false);
  });

  it("fails naming a lock hash that is not a file of that release", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30)]);
    const res = ageCheck(pin, r, NOW);
    assert.equal(res.ok, false);
    assert.deepEqual(res.unknownHashes, [h("b")]);
    assert.equal(res.holdBack, null);
  });

  it("fails a pin without hashes", () => {
    assert.equal(ageCheck({ ...pin, hashes: [] }, release("alpha", "1.0.0", []), NOW).ok, false);
  });
});

describe("yankCheck (b)", () => {
  const pin = { name: "alpha", version: "1.0.0", hashes: [h("a")] };

  it("passes a release whose matched files are not yanked", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30), file(h("e"), 30, { yanked: true })]);
    assert.equal(yankCheck(r, pin).ok, true);
  });

  it("fails a yanked release", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30)], { yanked: true });
    assert.equal(yankCheck(r, pin).ok, false);
  });

  it("fails a yanked matched file, naming it", () => {
    const r = release("alpha", "1.0.0", [file(h("a"), 30, { yanked: true })]);
    const res = yankCheck(r, pin);
    assert.equal(res.ok, false);
    assert.deepEqual(res.yanked, ["f-aaaa.whl"]);
  });

  it("without a pin, any yanked file of the release fails", () => {
    const r = release("alpha", "1.0.0", [file(h("e"), 30, { yanked: true })]);
    assert.equal(yankCheck(r).ok, false);
  });
});

describe("osvCheck (c)", () => {
  it("passes an empty result and fails listing the advisory ids", () => {
    assert.deepEqual(osvCheck({}), { ok: true, advisories: [] });
    assert.deepEqual(osvCheck({ vulns: [] }), { ok: true, advisories: [] });
    assert.deepEqual(
      osvCheck({
        vulns: [
          { id: "PYSEC-2026-1", modified: NOW },
          { id: "GHSA-xxxx-yyyy-zzzz", modified: NOW },
        ],
      }),
      { ok: false, advisories: ["GHSA-xxxx-yyyy-zzzz", "PYSEC-2026-1"] },
    );
  });

  it("fails a missing result (the query did not answer for this pin)", () => {
    assert.equal(osvCheck(undefined).ok, false);
  });
});

describe("legitimacyCheck (d)", () => {
  const r = release("alpha", "1.0.0", []);

  it("SLOP fails even with a matching repository", () => {
    assert.equal(legitimacyCheck(seam("alpha", "SLOP"), r, KNOWN).ok, false);
  });

  it("OK passes", () => {
    assert.equal(legitimacyCheck(seam("alpha", "OK"), r, KNOWN).ok, true);
  });

  it("SUS passes only when a project URL matches the known repository (host and path prefix, case-insensitive)", () => {
    const upper = release("alpha", "1.0.0", [], {
      project_urls: { Tracker: "https://GitHub.com/Example/Alpha/issues" },
    });
    const res = legitimacyCheck(seam("alpha"), upper, KNOWN);
    assert.equal(res.ok, true);
    assert.equal(res.matched, "https://GitHub.com/Example/Alpha/issues");
    const viaHome = release("alpha", "1.0.0", [], {
      project_urls: null,
      home_page: "https://github.com/example/alpha",
    });
    assert.equal(legitimacyCheck(seam("alpha"), viaHome, KNOWN).ok, true);
  });

  it("SUS fails on a look-alike repository or another host", () => {
    for (const url of [
      "https://github.com/example/alpha-fork",
      "https://github.com/exampl/alpha",
      "https://gitlab.com/example/alpha",
    ]) {
      const other = release("alpha", "1.0.0", [], { project_urls: { Source: url } });
      assert.equal(legitimacyCheck(seam("alpha"), other, KNOWN).ok, false, url);
    }
  });

  it("a name missing from KNOWN_PROJECTS fails, and so does a missing verdict", () => {
    assert.equal(legitimacyCheck(seam("delta", "OK"), release("delta", "1.0.0", []), KNOWN).ok, false);
    assert.equal(legitimacyCheck(undefined, r, KNOWN).ok, false);
  });

  it("KNOWN_PROJECTS names the pypdf, pdfplumber, pandas, numpy and Pillow repositories", () => {
    assert.ok(KNOWN_PROJECTS.pypdf.includes("github.com/py-pdf/pypdf"));
    assert.ok(KNOWN_PROJECTS.pdfplumber.includes("github.com/jsvine/pdfplumber"));
    assert.ok(KNOWN_PROJECTS.pandas.includes("github.com/pandas-dev/pandas"));
    assert.ok(KNOWN_PROJECTS.numpy.includes("github.com/numpy/numpy"));
    assert.ok(KNOWN_PROJECTS.pillow.includes("github.com/python-pillow/pillow"));
  });
});

describe("closureCheck (e)", () => {
  const pins = parseLock(LOCK);

  it("passes when every pin is a requirements.in name or reached from one", () => {
    assert.deepEqual(closureCheck(pins, ["alpha", "beta-lib"]), {
      ok: true,
      unreachable: [],
      unpinned: [],
    });
  });

  it("fails a pin reached from nothing", () => {
    const orphan = [...pins, { name: "omega", version: "1.0.0", hashes: [h("f")], via: ["nobody"] }];
    const res = closureCheck(orphan, ["alpha", "beta-lib"]);
    assert.equal(res.ok, false);
    assert.deepEqual(res.unreachable, ["omega"]);
  });

  it("fails a pin whose only parent is itself outside the closure", () => {
    const chain = [
      { name: "alpha", version: "1.0.0", hashes: [h("a")], via: ["-r requirements.in"] },
      { name: "x", version: "1", hashes: [h("b")], via: ["y"] },
      { name: "y", version: "1", hashes: [h("c")], via: ["x"] },
    ];
    assert.deepEqual(closureCheck(chain, ["alpha"]).unreachable, ["x", "y"]);
  });

  it("fails a requirements.in name that is not pinned", () => {
    const res = closureCheck(pins, ["alpha", "beta-lib", "zeta"]);
    assert.equal(res.ok, false);
    assert.deepEqual(res.unpinned, ["zeta"]);
  });
});

describe("installedCheck (f)", () => {
  const pins = parseLock(LOCK);

  it("passes equal maps and fails a missing or different version", () => {
    assert.equal(installedCheck(pins, { alpha: "1.0.0", Beta_Lib: "2.0.0", gamma: "3.0.0" }).ok, true);
    const res = installedCheck(pins, { alpha: "1.0.1", gamma: "3.0.0" });
    assert.equal(res.ok, false);
    assert.deepEqual(res.missing, ["beta-lib"]);
    assert.deepEqual(res.mismatched, ["alpha: installed 1.0.1, locked 1.0.0"]);
  });
});

describe("evidence", () => {
  const releases = {
    alpha: release("alpha", "1.0.0", [file(h("a"), 40), file(h("b"), 40)]),
    "beta-lib": release("beta-lib", "2.0.0", [file(h("c"), 40)]),
    gamma: release("gamma", "3.0.0", [file(h("d"), 40)]),
  };
  const osv = { alpha: {}, "beta-lib": {}, gamma: {} };
  const legitimacy = [seam("alpha"), seam("Beta_Lib"), seam("gamma")];
  const base = { lockText: LOCK, inText: IN, releases, osv, legitimacy, now: NOW, known: KNOWN };

  it("passes (a)-(e), carries the lock's sha256, sorted pins and no CI section without --installed", () => {
    const doc = evidence(base);
    assert.equal(doc.ok, true, JSON.stringify(doc.pass));
    assert.deepEqual(doc.pass, { a: true, b: true, c: true, d: true, e: true, f: null });
    assert.equal(doc.lockSha256, createHash("sha256").update(LOCK).digest("hex"));
    assert.equal(doc.generatedAt, NOW);
    assert.equal(doc.minAgeDays, 14);
    assert.deepEqual(
      doc.pins.map((p) => p.name),
      ["alpha", "beta-lib", "gamma"],
    );
    assert.deepEqual(doc.holdBack, []);
    assert.equal(doc.ci, null);
    assert.deepEqual(doc.closure.inNames, ["alpha", "beta-lib"]);
    assert.deepEqual(evidence(base), doc, "stable output");
  });

  it("ok is false when one check fails, and the hold-backs are listed", () => {
    const young = {
      ...releases,
      gamma: release("gamma", "3.0.0", [file(h("d"), 2)]),
    };
    const doc = evidence({ ...base, releases: young });
    assert.equal(doc.ok, false);
    assert.equal(doc.pass.a, false);
    assert.deepEqual(doc.holdBack, ["gamma<3.0.0"]);
    const advisory = evidence({ ...base, osv: { ...osv, alpha: { vulns: [{ id: "PYSEC-1" }] } } });
    assert.equal(advisory.pass.c, false);
    assert.equal(advisory.ok, false);
    const slop = evidence({ ...base, legitimacy: [seam("alpha", "SLOP"), ...legitimacy.slice(1)] });
    assert.equal(slop.pass.d, false);
    const missing = evidence({ ...base, releases: { alpha: releases.alpha, gamma: releases.gamma } });
    assert.equal(missing.pass.a, false);
    assert.equal(missing.pass.b, false);
  });

  it("with installed versions (f) also decides ok, and the CI run is recorded", () => {
    const installed = { alpha: "1.0.0", "beta-lib": "2.0.0", gamma: "3.0.0" };
    const doc = evidence({ ...base, installed, ciRun: "https://ci.example/run/1" });
    assert.equal(doc.ok, true);
    assert.equal(doc.pass.f, true);
    assert.deepEqual(doc.ci, { run: "https://ci.example/run/1", installedMatches: true });
    const wrong = evidence({ ...base, installed: { ...installed, gamma: "3.0.1" } });
    assert.equal(wrong.pass.f, false);
    assert.equal(wrong.ok, false);
  });
});
