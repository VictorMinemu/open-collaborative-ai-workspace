// systemd units for the runtime (07.12-04, D-04, PD-11, RESEARCH §4 and Pitfall 10). Absolute paths only, every value
// escaped for the directive it lands in, and nothing secret: no token, no key, no EnvironmentFile (service.env is read
// by `ocw-runtime run` itself, PD-10), no socket and no port. The text is compared byte for byte on re-install, so it
// must be a pure function of its inputs.

export const SYSTEMD_UNIT_NAME = "ocw-runtime.service";
export const SYSTEMD_SYSTEM_UNIT_DIR = "/etc/systemd/system";

const HEADER = "# Generated by ocw-runtime service install; re-run it instead of editing.";

// biome-ignore lint/suspicious/noControlCharactersInRegex: matching control characters is the point.
const CONTROL = /[\u0000-\u001f\u007f]/;

function assertNoControl(value: string): void {
  if (CONTROL.test(value))
    throw new Error("a path or value with a newline or control character cannot go in a unit");
}

/**
 * One ExecStart= word: double-quoted, with C-style `\` and `"` escaped, `%` (specifiers) as `%%` and `$` (variable
 * expansion) as `$$`. Refuses control characters, so a value can never start a new directive.
 */
export function systemdQuote(value: string): string {
  assertNoControl(value);
  const escaped = value
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("%", "%%")
    .replaceAll("$", "$$$$");
  return `"${escaped}"`;
}

/**
 * One Environment= assignment, double-quoted. systemd does not expand `$` there (it would stay `$$`), so only `\`,
 * `"` and `%` are escaped.
 */
export function systemdEnvQuote(name: string, value: string): string {
  if (!/^[A-Z_][A-Z0-9_]*$/.test(name)) throw new Error(`invalid environment name ${name}`);
  assertNoControl(value);
  const escaped = value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("%", "%%");
  return `"${name}=${escaped}"`;
}

/**
 * A path directive such as WorkingDirectory=: taken literally (no unquoting, no `$`), with specifiers expanded, so only
 * `%` is doubled. Must be absolute; trailing whitespace would be trimmed by the parser, so it is refused.
 */
export function systemdPathValue(path: string): string {
  assertNoControl(path);
  if (!path.startsWith("/")) throw new Error("a unit path must be absolute");
  if (/\s$/.test(path)) throw new Error("a unit path cannot end in whitespace");
  return path.replaceAll("%", "%%");
}

export interface SystemdUnitOptions {
  scope: "user" | "system";
  /** Absolute node binary. */
  nodePath: string;
  /** Absolute `<OCW_HOME>/runtime/current/ocw-runtime.mjs` (through the `current` link, never resolved). */
  bundlePath: string;
  /** The account's home directory. */
  workingDirectory: string;
  /** The PATH the service sees: the node directory first, then the installer's existing directories. */
  path: string;
  /** Set only when OCW_HOME is not the default `<home>/.ocw`. */
  ocwHome?: string;
  /** System units: the non-root account the runtime runs as (validated by the caller). */
  account?: string;
}

export function renderSystemdUnit(opts: SystemdUnitOptions): string {
  const system = opts.scope === "system";
  if (system && !opts.account) throw new Error("a system unit needs the account it runs as");
  const unit = [
    HEADER,
    "[Unit]",
    "Description=OCW Local Runtime (Work Zone device)",
    ...(system ? ["After=network-online.target", "Wants=network-online.target"] : []),
    "StartLimitIntervalSec=300",
    "StartLimitBurst=10",
    "",
    "[Service]",
    "Type=simple",
    ...(system ? [`User=${opts.account}`] : []),
    `ExecStart=${systemdQuote(opts.nodePath)} ${systemdQuote(opts.bundlePath)} run`,
    `WorkingDirectory=${systemdPathValue(opts.workingDirectory)}`,
    `Environment=${systemdEnvQuote("PATH", opts.path)}`,
    ...(opts.ocwHome ? [`Environment=${systemdEnvQuote("OCW_HOME", opts.ocwHome)}`] : []),
    "Restart=on-failure",
    "RestartSec=5",
    "KillMode=mixed",
    "TimeoutStopSec=20",
    "UMask=0077",
    "",
    "[Install]",
    `WantedBy=${system ? "multi-user.target" : "default.target"}`,
  ];
  return `${unit.join("\n")}\n`;
}

function unquoteWord(word: string): string {
  return word
    .slice(1, -1)
    .replace(/\\(["\\])/g, "$1")
    .replaceAll("%%", "%")
    .replaceAll("$$", "$");
}

/** The node and bundle paths a unit runs (for status and doctor), or null when the unit is not ours. */
export function parseSystemdExecStart(unit: string): { nodePath: string; bundlePath: string } | null {
  const line = unit.split("\n").find((l) => l.startsWith("ExecStart="));
  if (!line) return null;
  const words = line.slice("ExecStart=".length).match(/"(?:[^"\\]|\\.)*"/g);
  if (!words || words.length < 2) return null;
  return { nodePath: unquoteWord(words[0]!), bundlePath: unquoteWord(words[1]!) };
}
