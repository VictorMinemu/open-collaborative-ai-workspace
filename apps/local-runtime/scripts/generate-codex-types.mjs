#!/usr/bin/env node
// Regenerates src/codex/generated/ from the INSTALLED codex CLI:
//   codex app-server generate-ts --out <tmp>
// and copies only the import closure of the protocol types the adapter uses (the full output is
// ~700 files). Re-run after upgrading codex, then re-record the fixture.
//
//   node scripts/generate-codex-types.mjs [--codex /path/to/codex]

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, normalize, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOTS = [
  "InitializeParams",
  "InitializeResponse",
  "v2/ThreadStartParams",
  "v2/ThreadStartResponse",
  "v2/ThreadResumeParams",
  "v2/ThreadResumeResponse",
  "v2/TurnStartParams",
  "v2/TurnStartResponse",
  "v2/TurnSteerParams",
  "v2/TurnInterruptParams",
  "v2/ThreadStartedNotification",
  "v2/TurnStartedNotification",
  "v2/TurnCompletedNotification",
  "v2/ItemStartedNotification",
  "v2/ItemCompletedNotification",
  "v2/AgentMessageDeltaNotification",
  "v2/ThreadTokenUsageUpdatedNotification",
  "v2/ErrorNotification",
  "v2/CommandExecutionRequestApprovalParams",
  "v2/CommandExecutionRequestApprovalResponse",
  "v2/FileChangeRequestApprovalParams",
  "v2/FileChangeRequestApprovalResponse",
  "v2/PermissionsRequestApprovalParams",
  "v2/PermissionsRequestApprovalResponse",
  "v2/ThreadStatusChangedNotification",
  "ExecCommandApprovalParams",
  "ExecCommandApprovalResponse",
  "ApplyPatchApprovalParams",
  "ApplyPatchApprovalResponse",
  "RequestId",
  // Phase 03.2 (session controls): catalog, effective-settings readback and native compaction.
  "v2/ModelListParams",
  "v2/ModelListResponse",
  "v2/Model",
  "v2/ThreadSettingsUpdatedNotification",
  "v2/ThreadSettings",
  "v2/ThreadCompactStartParams",
];

const argIdx = process.argv.indexOf("--codex");
const codex = argIdx > 0 ? process.argv[argIdx + 1] : "codex";
const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "src", "codex", "generated");
const tmp = mkdtempSync(join(tmpdir(), "ocw-codex-ts-"));

try {
  const version = execFileSync(codex, ["--version"], { encoding: "utf8" }).trim();
  execFileSync(codex, ["app-server", "generate-ts", "--out", tmp], { stdio: "inherit" });

  const seen = new Set();
  const stack = ROOTS.map((r) => normalize(join(tmp, `${r}.ts`)));
  while (stack.length > 0) {
    const file = stack.pop();
    if (seen.has(file) || !existsSync(file)) continue;
    seen.add(file);
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/from "(\.[^"]+)"/g)) {
      const spec = m[1];
      stack.push(normalize(join(dirname(file), spec.endsWith(".ts") ? spec : `${spec}.ts`)));
    }
  }

  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const file of seen) {
    const dest = join(outDir, relative(tmp, file));
    mkdirSync(dirname(dest), { recursive: true });
    // NodeNext resolution needs explicit extensions on relative imports.
    const src = readFileSync(file, "utf8").replace(/from "(\.[^"]+?)(\.ts)?"/g, 'from "$1.js"');
    writeFileSync(dest, src);
  }
  writeFileSync(
    join(outDir, "VERSION"),
    `Generated by \`codex app-server generate-ts\` from ${version}; import closure of ${ROOTS.length} roots (${seen.size} files).\n`,
  );
  console.log(`codex types: ${seen.size} files from ${version} -> src/codex/generated/`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
