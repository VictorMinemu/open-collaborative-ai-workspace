// The macOS LaunchAgent for the runtime (07.12-04, D-04, PD-11, RESEARCH §4 and Pitfall 9). `KeepAlive` restarts it
// only after a failure (the daemon exits 0 on SIGTERM, so a stopped agent stays stopped), `ProcessType Standard`
// avoids the background CPU and I/O throttling, and every value is XML-escaped. No secret, socket or port.

export const LAUNCHD_LABEL = "org.ocw.runtime";
export const LAUNCHD_PLIST_FILE = `${LAUNCHD_LABEL}.plist`;

// biome-ignore lint/suspicious/noControlCharactersInRegex: matching control characters is the point.
const CONTROL = /[\u0000-\u001f\u007f]/;

/** Escape a value for a plist `<string>`; control characters (not representable in XML 1.0) are refused. */
export function xmlEscape(value: string): string {
  if (CONTROL.test(value))
    throw new Error("a path or value with a newline or control character cannot go in a plist");
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function xmlUnescape(value: string): string {
  return value
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&apos;", "'")
    .replaceAll("&amp;", "&");
}

export interface LaunchdPlistOptions {
  nodePath: string;
  /** `<OCW_HOME>/runtime/current/ocw-runtime.mjs` (through the `current` link). */
  bundlePath: string;
  workingDirectory: string;
  path: string;
  /** `<OCW_HOME>/logs/runtime.log`: stdout and stderr. */
  logFile: string;
  /** Set only when OCW_HOME is not the default. */
  ocwHome?: string;
}

export function renderLaunchdPlist(opts: LaunchdPlistOptions): string {
  const s = (v: string) => `<string>${xmlEscape(v)}</string>`;
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    "<!-- Generated by ocw-runtime service install; re-run it instead of editing. -->",
    '<plist version="1.0">',
    "<dict>",
    "  <key>Label</key>",
    `  ${s(LAUNCHD_LABEL)}`,
    "  <key>ProgramArguments</key>",
    "  <array>",
    `    ${s(opts.nodePath)}`,
    `    ${s(opts.bundlePath)}`,
    `    ${s("run")}`,
    "  </array>",
    "  <key>RunAtLoad</key>",
    "  <true/>",
    "  <key>KeepAlive</key>",
    "  <dict>",
    "    <key>SuccessfulExit</key>",
    "    <false/>",
    "  </dict>",
    "  <key>ProcessType</key>",
    `  ${s("Standard")}`,
    "  <key>WorkingDirectory</key>",
    `  ${s(opts.workingDirectory)}`,
    "  <key>EnvironmentVariables</key>",
    "  <dict>",
    "    <key>PATH</key>",
    `    ${s(opts.path)}`,
    ...(opts.ocwHome ? ["    <key>OCW_HOME</key>", `    ${s(opts.ocwHome)}`] : []),
    "  </dict>",
    "  <key>StandardOutPath</key>",
    `  ${s(opts.logFile)}`,
    "  <key>StandardErrorPath</key>",
    `  ${s(opts.logFile)}`,
    "</dict>",
    "</plist>",
  ];
  return `${lines.join("\n")}\n`;
}

/** The node and bundle paths a plist runs (for status and doctor), or null when it is not ours. */
export function parseLaunchdProgramArguments(plist: string): { nodePath: string; bundlePath: string } | null {
  const m =
    /<key>ProgramArguments<\/key>\s*<array>\s*<string>([^<]*)<\/string>\s*<string>([^<]*)<\/string>/.exec(
      plist,
    );
  if (!m) return null;
  return { nodePath: xmlUnescape(m[1]!), bundlePath: xmlUnescape(m[2]!) };
}

/** `launchctl print gui/<uid>/<label>`: the service's own (top-level, one tab deep) state and pid. */
export function parseLaunchctlPrint(text: string): { state: string | null; pid: number | null } {
  const state = /^\tstate = (.+)$/m.exec(text)?.[1]?.trim() ?? null;
  const pid = /^\tpid = (\d+)$/m.exec(text)?.[1];
  return { state, pid: pid ? Number(pid) : null };
}
