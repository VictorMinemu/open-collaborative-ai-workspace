import { describe, expect, it } from "vitest";
import {
  isValidAccountName,
  parseSystemdExecStart,
  renderSystemdUnit,
  SYSTEMD_UNIT_NAME,
  systemdEnvQuote,
  systemdPathValue,
  systemdQuote,
} from "./systemd.js";

const USER_UNIT = `# Generated by ocw-runtime service install; re-run it instead of editing.
[Unit]
Description=OCW Local Runtime (Work Zone device)
StartLimitIntervalSec=300
StartLimitBurst=10

[Service]
Type=simple
ExecStart="/usr/local/bin/node" "/home/alice/.ocw/runtime/current/ocw-runtime.mjs" run
WorkingDirectory=/home/alice
Environment="PATH=/usr/local/bin:/usr/bin:/bin"
Restart=on-failure
RestartSec=5
KillMode=mixed
TimeoutStopSec=20
UMask=0077

[Install]
WantedBy=default.target
`;

describe("systemd quoting (07.12, PD-11, RESEARCH Pitfall 10)", () => {
  it('double-quotes and escapes \\, ", % and $ for ExecStart', () => {
    expect(SYSTEMD_UNIT_NAME).toBe("ocw-runtime.service");
    expect(systemdQuote("/a b")).toBe('"/a b"');
    expect(systemdQuote('/home/a b%c$d"e\\f')).toBe('"/home/a b%%c$$d\\"e\\\\f"');
  });

  it("refuses newlines and other control characters", () => {
    expect(() => systemdQuote("/home/a\nb")).toThrow(/control character/);
    expect(() => systemdQuote("/home/a\tb")).toThrow(/control character/);
    expect(() => systemdQuote("/home/a\u007fb")).toThrow(/control character/);
  });

  it("keeps $ literal in Environment= (systemd does not expand variables there)", () => {
    expect(systemdEnvQuote("PATH", "/opt/a$b%c")).toBe('"PATH=/opt/a$b%%c"');
    expect(() => systemdEnvQuote("PATH", "/a\nb")).toThrow(/control character/);
  });

  it("writes WorkingDirectory literally (no unquoting there), only % doubled", () => {
    expect(systemdPathValue("/srv/build home/50%")).toBe("/srv/build home/50%%");
    expect(() => systemdPathValue("relative/dir")).toThrow(/absolute/);
    expect(() => systemdPathValue("/home/a ")).toThrow(/whitespace/);
  });

  it("reads back the node and bundle paths from ExecStart", () => {
    const unit = renderSystemdUnit({
      scope: "user",
      nodePath: '/home/a b%c$d"e\\f/node',
      bundlePath: "/home/x/.ocw/runtime/current/ocw-runtime.mjs",
      workingDirectory: "/home/x",
      path: "/usr/bin",
    });
    expect(parseSystemdExecStart(unit)).toEqual({
      nodePath: '/home/a b%c$d"e\\f/node',
      bundlePath: "/home/x/.ocw/runtime/current/ocw-runtime.mjs",
    });
    expect(parseSystemdExecStart("[Service]\nType=simple\n")).toBeNull();
  });
});

describe("renderSystemdUnit, user scope (07.12, D-04, PD-11)", () => {
  const unit = renderSystemdUnit({
    scope: "user",
    nodePath: "/usr/local/bin/node",
    bundlePath: "/home/alice/.ocw/runtime/current/ocw-runtime.mjs",
    workingDirectory: "/home/alice",
    path: "/usr/local/bin:/usr/bin:/bin",
  });

  it("equals the snapshot", () => {
    expect(unit).toBe(USER_UNIT);
  });

  it("has no secret, no specifier, no socket and no system target", () => {
    expect(unit).not.toMatch(/EnvironmentFile|service\.env|TOKEN|KEY|SECRET|Listen/i);
    // Every % is doubled: no %h, %u or any other specifier survives.
    expect(unit.replaceAll("%%", "")).not.toContain("%");
    expect(unit).not.toContain("network-online.target");
    expect(unit).not.toContain("User=");
  });

  it("names OCW_HOME only when it is not the default", () => {
    const custom = renderSystemdUnit({
      scope: "user",
      nodePath: "/usr/bin/node",
      bundlePath: "/srv/ocw/runtime/current/ocw-runtime.mjs",
      workingDirectory: "/home/alice",
      path: "/usr/bin",
      ocwHome: "/srv/ocw",
    });
    expect(custom).toContain('Environment="OCW_HOME=/srv/ocw"\n');
    expect(unit).not.toContain("OCW_HOME");
  });

  it("escapes a hostile home and stays one ExecStart line", () => {
    const home = '/home/a b%c$d"e';
    const hostile = renderSystemdUnit({
      scope: "user",
      nodePath: "/usr/bin/node",
      bundlePath: `${home}/.ocw/runtime/current/ocw-runtime.mjs`,
      workingDirectory: home,
      path: "/usr/bin",
    });
    const exec = hostile.split("\n").filter((l) => l.startsWith("ExecStart="));
    expect(exec).toEqual([
      'ExecStart="/usr/bin/node" "/home/a b%%c$$d\\"e/.ocw/runtime/current/ocw-runtime.mjs" run',
    ]);
    expect(hostile).toContain('WorkingDirectory=/home/a b%%c$d"e\n');
  });

  it("refuses a path with a newline", () => {
    expect(() =>
      renderSystemdUnit({
        scope: "user",
        nodePath: "/usr/bin/node",
        bundlePath: "/home/a\nExecStartPre=/bin/sh/.ocw/runtime/current/ocw-runtime.mjs",
        workingDirectory: "/home/a",
        path: "/usr/bin",
      }),
    ).toThrow(/control character/);
  });
});

const SYSTEM_UNIT = `# Generated by ocw-runtime service install; re-run it instead of editing.
[Unit]
Description=OCW Local Runtime (Work Zone device)
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=300
StartLimitBurst=10

[Service]
Type=simple
User=build
ExecStart="/usr/bin/node" "/srv/build home/.ocw/runtime/current/ocw-runtime.mjs" run
WorkingDirectory=/srv/build home
Environment="PATH=/usr/bin:/bin"
Restart=on-failure
RestartSec=5
KillMode=mixed
TimeoutStopSec=20
UMask=0077

[Install]
WantedBy=multi-user.target
`;

describe("renderSystemdUnit, system scope (07.12, D-04, PD-11)", () => {
  it("equals the snapshot: User=, network-online.target, multi-user.target", () => {
    expect(
      renderSystemdUnit({
        scope: "system",
        account: "build",
        nodePath: "/usr/bin/node",
        bundlePath: "/srv/build home/.ocw/runtime/current/ocw-runtime.mjs",
        workingDirectory: "/srv/build home",
        path: "/usr/bin:/bin",
      }),
    ).toBe(SYSTEM_UNIT);
  });

  it("needs a valid non-root account", () => {
    const base = {
      scope: "system" as const,
      nodePath: "/usr/bin/node",
      bundlePath: "/srv/b/.ocw/runtime/current/ocw-runtime.mjs",
      workingDirectory: "/srv/b",
      path: "/usr/bin",
    };
    expect(() => renderSystemdUnit(base)).toThrow(/account/);
    expect(() => renderSystemdUnit({ ...base, account: "root" })).toThrow(/root/);
    expect(() => renderSystemdUnit({ ...base, account: "bad;name" })).toThrow(/invalid account/);
    expect(isValidAccountName("build")).toBe(true);
    expect(isValidAccountName("svc-ocw_1")).toBe(true);
    expect(isValidAccountName("machine$")).toBe(true);
    expect(isValidAccountName("Bad")).toBe(false);
    expect(isValidAccountName("-x")).toBe(false);
    expect(isValidAccountName("a b")).toBe(false);
  });
});
