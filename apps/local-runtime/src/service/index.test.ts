import { existsSync, readFileSync, statSync } from "node:fs";
import { afterEach, describe, expect, it } from "vitest";
import { createServiceManager, serviceCommand } from "./index.js";
import { cleanupRoots, harness, NODE } from "./test-harness.js";

afterEach(() => cleanupRoots());

const USER_UNIT_PATH = "/home/alice/.config/systemd/user/ocw-runtime.service";

const EXPECTED_USER_UNIT = `# Generated by ocw-runtime service install; re-run it instead of editing.
[Unit]
Description=OCW Local Runtime (Work Zone device)
StartLimitIntervalSec=300
StartLimitBurst=10

[Service]
Type=simple
ExecStart="/opt/node/bin/node" "/home/alice/.ocw/runtime/current/ocw-runtime.mjs" run
WorkingDirectory=/home/alice
Environment="PATH=/opt/node/bin:/usr/bin:/bin"
Restart=on-failure
RestartSec=5
KillMode=mixed
TimeoutStopSec=20
UMask=0077

[Install]
WantedBy=default.target
`;

/** A systemd user manager that answers like a real one after `enable --now`. */
function systemdUser(linger: "yes" | "no" = "no") {
  return (argv: string[]) => {
    const cmd = argv.join(" ");
    if (cmd === "systemctl --user is-active ocw-runtime.service") return { stdout: "active\n" };
    if (cmd === "systemctl --user is-enabled ocw-runtime.service") return { stdout: "enabled\n" };
    if (cmd === "loginctl show-user alice --property=Linger") return { stdout: `Linger=${linger}\n` };
    return undefined;
  };
}

describe("service install on a systemd user manager (07.12, D-04, PD-11)", () => {
  it("writes the unit (0644), enables it, checks it and prints the linger line", async () => {
    const h = harness({ exec: systemdUser("no") });
    const code = await serviceCommand(["install"], h.deps);
    expect(code).toBe(0);

    const file = h.at(USER_UNIT_PATH);
    expect(readFileSync(file, "utf8")).toBe(EXPECTED_USER_UNIT);
    expect(statSync(file).mode & 0o777).toBe(0o644);
    expect(h.calls).toEqual([
      ["systemctl", "--user", "show-environment"],
      ["systemctl", "--user", "daemon-reload"],
      ["systemctl", "--user", "enable", "--now", "ocw-runtime.service"],
      ["systemctl", "--user", "is-active", "ocw-runtime.service"],
      ["loginctl", "show-user", "alice", "--property=Linger"],
    ]);
    const text = h.lines.join("\n");
    expect(text).toContain("sudo loginctl enable-linger alice");
    expect(text).toContain("~/.config/systemd/user/ocw-runtime.service");
    // Paths are shown home-relative, never as the absolute home.
    expect(text).not.toContain("/home/alice");
  });

  it("does not print the linger line when lingering is on", async () => {
    const h = harness({ exec: systemdUser("yes") });
    expect(await serviceCommand(["install"], h.deps)).toBe(0);
    expect(h.lines.join("\n")).not.toContain("enable-linger");
  });

  it("honours XDG_CONFIG_HOME", async () => {
    const h = harness({
      exec: systemdUser(),
      env: { PATH: "/usr/bin", XDG_CONFIG_HOME: "/home/alice/.cfg" },
    });
    expect(await serviceCommand(["install"], h.deps)).toBe(0);
    expect(existsSync(h.at("/home/alice/.cfg/systemd/user/ocw-runtime.service"))).toBe(true);
    expect(existsSync(h.at(USER_UNIT_PATH))).toBe(false);
  });

  it("reports the ServiceStatus doctor and setup consume", async () => {
    const h = harness({ exec: systemdUser("no") });
    const manager = createServiceManager(h.deps);
    const installed = await manager.install({ manager: "systemd-user" });
    expect(installed.ok).toBe(true);
    expect(await manager.status()).toEqual({
      manager: "systemd-user",
      installed: true,
      enabled: true,
      active: true,
      linger: false,
      account: "alice",
      unitPath: "~/.config/systemd/user/ocw-runtime.service",
      nodePathExists: true,
      bundlePathExists: true,
      reason: null,
    });
  });

  it("status sees a node that an nvm upgrade removed", async () => {
    const h = harness({ exec: systemdUser("yes") });
    const manager = createServiceManager(h.deps);
    await manager.install({ manager: "systemd-user" });
    const { rmSync } = await import("node:fs");
    rmSync(h.at(NODE));
    const status = await manager.status();
    expect(status.nodePathExists).toBe(false);
    expect(status.bundlePathExists).toBe(true);
  });

  it("status when nothing is installed", async () => {
    const h = harness({ exec: systemdUser() });
    expect(await createServiceManager(h.deps).status()).toEqual({
      manager: "systemd-user",
      installed: false,
      enabled: null,
      active: null,
      linger: null,
      account: "alice",
      unitPath: null,
      nodePathExists: null,
      bundlePathExists: null,
      reason: null,
    });
  });

  it("the unit carries no secret, specifier or port, and PATH holds existing directories once", async () => {
    const h = harness({
      exec: systemdUser(),
      env: {
        PATH: "/opt/node/bin:/usr/bin:/nonexistent:/bin:/usr/bin:relative/bin",
        CLAUDE_CODE_OAUTH_TOKEN: "sk-ant-oat01-secret",
        OPENAI_API_KEY: "sk-secret",
      },
    });
    h.write("/home/alice/.ocw/service.env", "CLAUDE_CODE_OAUTH_TOKEN=sk-ant-oat01-secret\n");
    expect(await serviceCommand(["install"], h.deps)).toBe(0);
    const unit = readFileSync(h.at(USER_UNIT_PATH), "utf8");
    expect(unit).toContain('Environment="PATH=/opt/node/bin:/usr/bin:/bin"\n');
    expect(unit).not.toMatch(/secret|sk-|EnvironmentFile|service\.env|Listen|%h/i);
    expect(unit.replaceAll("%%", "")).not.toContain("%");
  });

  it("falls back to this node when the one in install.json is gone", async () => {
    const h = harness({ exec: systemdUser("yes") });
    h.write(
      "/home/alice/.ocw/runtime/install.json",
      JSON.stringify({
        serverUrl: "https://ocw.example.com",
        version: "0.1.0",
        sha256: "a".repeat(64),
        installedAt: "2026-10-29T10:00:00.000Z",
        nodePath: "/gone/node",
      }),
    );
    h.write("/usr/bin/node-current", "#!/bin/sh\n");
    expect(await serviceCommand(["install"], h.deps)).toBe(0);
    const unit = readFileSync(h.at(USER_UNIT_PATH), "utf8");
    expect(unit).toContain('ExecStart="/usr/bin/node-current" ');
    expect(unit).toContain('Environment="PATH=/usr/bin:/opt/node/bin:/bin"\n');
  });

  it("refuses without an installed bundle and writes nothing", async () => {
    const h = harness({ installed: false, exec: systemdUser() });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(h.lines.join("\n")).toContain(
      "install the runtime with the command from Settings › Devices first",
    );
    expect(existsSync(h.at("/home/alice/.config"))).toBe(false);
    expect(h.calls.filter((c) => c[1] !== "--user" || c[2] !== "show-environment")).toEqual([]);
  });

  it("refuses when the bundle link is missing even with install.json", async () => {
    const h = harness({ exec: systemdUser() });
    const { rmSync } = await import("node:fs");
    rmSync(h.at("/home/alice/.ocw/runtime/current"), { recursive: true });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(existsSync(h.at(USER_UNIT_PATH))).toBe(false);
  });

  it("refuses when the user manager is not reachable, with the SSH line", async () => {
    const h = harness({
      exec: (argv) => (argv.join(" ") === "systemctl --user show-environment" ? { code: 1 } : undefined),
    });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(h.lines.join("\n")).toContain("log in as alice over SSH (or machinectl shell alice@) and re-run");
    expect(existsSync(h.at("/home/alice/.config"))).toBe(false);
  });

  it("refuses where there is no service manager, with the supervisor line", async () => {
    const h = harness({ systemd: false });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(h.lines.join("\n")).toContain("run `ocw-runtime run` under your own supervisor");
    expect(h.calls).toEqual([]);
  });

  it("refuses a user unit as root (the runtime never runs as root)", async () => {
    const h = harness({ uid: 0, account: "root", home: "/root", exec: systemdUser() });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(h.lines.join("\n")).toContain("--system --user-name <account>");
    expect(existsSync(h.at("/root/.config"))).toBe(false);
  });

  it("surfaces a failed enable with exit 1", async () => {
    const h = harness({
      exec: (argv) =>
        argv.includes("enable")
          ? { code: 1, stderr: "Failed to enable unit: Unit file is masked.\n" }
          : undefined,
    });
    expect(await serviceCommand(["install"], h.deps)).toBe(1);
    expect(h.lines.join("\n")).toContain("Unit file is masked");
  });
});

describe("service uninstall, restart and logs on a systemd user manager (07.12, D-04)", () => {
  it("uninstall disables, removes the file and reloads", async () => {
    const h = harness({ exec: systemdUser("yes") });
    await serviceCommand(["install"], h.deps);
    h.calls.length = 0;
    expect(await serviceCommand(["uninstall"], h.deps)).toBe(0);
    expect(existsSync(h.at(USER_UNIT_PATH))).toBe(false);
    expect(h.calls).toEqual([
      ["systemctl", "--user", "disable", "--now", "ocw-runtime.service"],
      ["systemctl", "--user", "daemon-reload"],
    ]);
  });

  it("uninstall with nothing installed says so", async () => {
    const h = harness({ exec: systemdUser() });
    expect(await serviceCommand(["uninstall"], h.deps)).toBe(0);
    expect(h.lines.join("\n")).toContain("not installed");
  });

  it("restart restarts the unit", async () => {
    const h = harness({ exec: systemdUser("yes") });
    await serviceCommand(["install"], h.deps);
    h.calls.length = 0;
    expect(await serviceCommand(["restart"], h.deps)).toBe(0);
    expect(h.calls).toEqual([["systemctl", "--user", "restart", "ocw-runtime.service"]]);
  });

  it("logs reads the user journal, -n and --follow", async () => {
    const h = harness({
      exec: (argv) => (argv[0] === "journalctl" ? { stdout: "line one\nline two\n" } : systemdUser()(argv)),
    });
    await serviceCommand(["install"], h.deps);
    h.calls.length = 0;
    h.lines.length = 0;
    expect(await serviceCommand(["logs"], h.deps)).toBe(0);
    expect(h.calls).toEqual([
      ["journalctl", "--user", "-u", "ocw-runtime.service", "-n", "200", "--no-pager"],
    ]);
    expect(h.lines).toEqual(["line one", "line two"]);
    h.calls.length = 0;
    expect(await serviceCommand(["logs", "-n", "50", "--follow"], h.deps)).toBe(0);
    expect(h.calls).toEqual([
      ["journalctl", "--user", "-u", "ocw-runtime.service", "-n", "50", "--no-pager", "-f"],
    ]);
    expect(await createServiceManager(h.deps).logs({ lines: 200, follow: false })).toBe(0);
  });

  it("status --json prints the ServiceStatus", async () => {
    const h = harness({ exec: systemdUser("yes") });
    await serviceCommand(["install"], h.deps);
    h.lines.length = 0;
    expect(await serviceCommand(["status", "--json"], h.deps)).toBe(0);
    const parsed = JSON.parse(h.lines.join("\n")) as Record<string, unknown>;
    expect(parsed.manager).toBe("systemd-user");
    expect(parsed.active).toBe(true);
    expect(parsed.linger).toBe(true);
  });

  it("rejects an unknown subcommand or a bad -n", async () => {
    const h = harness();
    expect(await serviceCommand(["frobnicate"], h.deps)).toBe(1);
    expect(await serviceCommand(["logs", "-n", "abc"], h.deps)).toBe(1);
    expect(await serviceCommand([], h.deps)).toBe(1);
  });
});
